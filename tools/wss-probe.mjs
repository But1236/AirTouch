#!/usr/bin/env node
/*
 * wss-probe.mjs - independent end-to-end probe of the AirTouch WSS endpoint.
 *
 * Why this exists: a C# client on Windows verifies TLS with the same Schannel stack the server uses,
 * which makes it a weak check of the handshake (and on a locked-down process token Schannel cannot
 * acquire client credentials at all). Node uses
 * its own OpenSSL stack - the same TLS family Android's OkHttp/Conscrypt uses - so this probe
 * verifies the real, production-configuration wss:// endpoint:
 *
 *   1. TLS handshake against the self-signed certificate, with an explicit SHA-256 fingerprint check
 *   2. RFC 6455 upgrade handshake (verifying Sec-WebSocket-Accept)
 *   3. protocol v2 authentication (§1.2): auth_challenge -> ECDSA P-256 auth_req -> welcome, with a
 *      device key generated by Node's OpenSSL. This is the only place where the canonical signed byte
 *      string, the SPKI encoding, the keyId hash and the DER signature are checked against a third,
 *      independent implementation (the app uses AndroidKeyStore, the server uses CNG).
 *   4. negative authentication paths: forged token, tampered signature, clock skew beyond the window,
 *      untrusted device key (resume), replayed one-time token, three-strike IP ban
 *   5. key-based resume with **no token at all** (the phone reconnecting after a dropped Wi-Fi link)
 *   6. control frames (move / moveto / click / scroll / reset), including a communication test
 *      (diag_begin -> seq-tagged moveto -> diag_report) whose report proves `moveto` bypasses
 *      Windows pointer ballistics
 *   7. client -> server file upload with a hostile file name, verified on disk
 *   8. server-initiated ping being answered (client replies with a pong frame)
 *
 * Usage (the server URL/token/fingerprint come from the server's stdout lines):
 *   node tools/wss-probe.mjs --url "wss://127.0.0.1:8443/ws?token=...&sid=...&fp=..." \
 *        --fingerprint "AA:BB:..." --download "C:\...\downloads"
 */
