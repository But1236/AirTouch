if (process.env.AIRTOUCH_PROBE_REPORT) {
  writeFileSync(process.env.AIRTOUCH_PROBE_REPORT, JSON.stringify({ results, failures }, null, 2));
}

process.exit(failures === 0 ? 0 : 1);
